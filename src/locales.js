const localeNames = { en: 'English', az: 'Azərbaycan', ru: 'Русский' };
let locale = localStorage.getItem('superpdf-locale');
if (!Object.hasOwn(localeNames, locale)) {
  const language = navigator.language.toLowerCase();
  locale = language.startsWith('az') ? 'az' : language.startsWith('ru') ? 'ru' : 'en';
}
const originalText = new WeakMap();
const originalAttributes = new WeakMap();

export function t(text) {
  const dictionary = translations[locale] || translations.en;
  const source = Object.entries(translations).find(([, values]) =>
    Object.entries(values).some(([key, value]) => value === text && key !== value))?.[1];
  const englishKey = source
    ? Object.entries(source).find(([, value]) => value === text)?.[0]
    : text;
  if (dictionary[englishKey]) return dictionary[englishKey];
  const match = text.match(/^Page (\d+) ready · local workspace$/);
  if (match && locale === 'az') return `Səhifə ${match[1]} hazır · yerli iş sahəsi`;
  if (match && locale === 'ru') return `Страница ${match[1]} готова · локальная рабочая область`;
  const pageLabel = text.match(/^Page (\d+)$/);
  if (pageLabel && locale === 'az') return `${pageLabel[1]}-ci səhifə`;
  if (pageLabel && locale === 'ru') return `Страница ${pageLabel[1]}`;
  const opening = text.match(/^Opening (.+)…$/);
  if (opening && locale === 'az') return `${opening[1]} açılır…`;
  if (opening && locale === 'ru') return `Открытие ${opening[1]}…`;
  const opened = text.match(/^(.+) opened locally$/);
  if (opened && locale === 'az') return `${opened[1]} yerli açıldı`;
  if (opened && locale === 'ru') return `${opened[1]} открыт локально`;
  const pageExported = text.match(/^Page (\d+) exported$/);
  if (pageExported && locale === 'az') return `${pageExported[1]}-ci səhifə ixrac edildi`;
  if (pageExported && locale === 'ru') return `Страница ${pageExported[1]} экспортирована`;
  const merge = text.match(/^(\d+) PDFs merged$/);
  if (merge && locale === 'az') return `${merge[1]} PDF birləşdirildi`;
  if (merge && locale === 'ru') return `Объединено PDF: ${merge[1]}`;
  const matches = text.match(/^(\d+) matches? across the document$/);
  if (matches && locale === 'az') return `Sənəddə ${matches[1]} uyğunluq tapıldı`;
  if (matches && locale === 'ru') return `Совпадений в документе: ${matches[1]}`;
  const pageSearch = text.match(/^Searching page (\d+)(?: of (\d+))?…$/);
  if (pageSearch && locale === 'az') return `${pageSearch[1]}${pageSearch[2] ? ` / ${pageSearch[2]}` : ''}-ci səhifədə axtarılır…`;
  if (pageSearch && locale === 'ru') return `Поиск на странице ${pageSearch[1]}${pageSearch[2] ? ` из ${pageSearch[2]}` : ''}…`;
  if (text === 'No matches found.' && locale === 'az') return 'Uyğunluq tapılmadı.';
  if (text === 'No matches found.' && locale === 'ru') return 'Совпадений не найдено.';
  if (text === 'Appearance · light' && locale === 'az') return 'Görünüş · açıq';
  if (text === 'Appearance · dark' && locale === 'az') return 'Görünüş · tünd';
  if (text === 'Appearance · light' && locale === 'ru') return 'Внешний вид · светлая';
  if (text === 'Appearance · dark' && locale === 'ru') return 'Внешний вид · тёмная';
  return text;
}

export function getLocale() {
  return locale;
}

export function setLocale(nextLocale) {
  if (!Object.hasOwn(localeNames, nextLocale)) throw new Error(`Unsupported language: ${nextLocale}`);
  locale = nextLocale;
  localStorage.setItem('superpdf-locale', locale);
  translateDocument();
}

export function translateDocument() {
  const dictionary = translations[locale] || translations.en;
  document.documentElement.lang = locale;
  document.title = 'Super PDF Studio';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const value = originalText.get(node);
    const trimmed = value.trim();
    node.nodeValue = dictionary[trimmed] ? value.replace(trimmed, dictionary[trimmed]) : value;
  }
  for (const element of document.querySelectorAll('[placeholder], [title], [aria-label]')) {
    if (!originalAttributes.has(element)) {
      originalAttributes.set(element, Object.fromEntries(['placeholder', 'title', 'aria-label']
        .map((attribute) => [attribute, element.getAttribute(attribute)])));
    }
    const originals = originalAttributes.get(element);
    for (const attribute of ['placeholder', 'title', 'aria-label']) {
      const value = originals[attribute];
      if (value && dictionary[value]) element.setAttribute(attribute, dictionary[value]);
      else if (value) element.setAttribute(attribute, value);
    }
  }
  document.querySelectorAll('#language-select option').forEach((option) => {
    option.textContent = localeNames[option.value];
  });
  const selector = document.getElementById('language-select');
  if (selector) selector.value = locale;
}
